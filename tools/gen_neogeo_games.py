"""Generates machines/neogeo/neogeo_games_data.inc from MAME's Neo Geo driver.

Usage: tools/gen_neogeo_games.py /path/to/mame/src/mame/snk > machines/neogeo/neogeo_games_data.inc

Takes every parent game that runs on the standard MVS board in MAME
("neobase" machine, no protection or encryption device, standard inputs):
title, year, maker and its ROM list (files, CRCs, offsets, layouts). The
BIOS files (sp-s2.sp1 etc.) are chosen at run time by the machine module.
Data is MAME's (BSD-3-Clause, copyright-holders: Bryan McPhail, Ernesto
Corvi, Andrew Prime, Zsolt Vasvari); see machines/neogeo/LICENSE-MAME.
"""
import re
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from gen_cps1_games import call_args, expand, load_macros, num, split_args  # noqa: E402

SKIP = {"mvstemp"}  # development cartridge, not a game
REGION_NAMES = {
    "cslot1:maincpu": "maincpu", "maincpu": "maincpu",
    "cslot1:fixed": "fixed", "fixedbios": "fixedbios",
    "spritegen:zoomy": "zoomy", "audiobios": "audiobios",
    "cslot1:audiocpu": "audiocpu", "cslot1:ymsnd:adpcma": "adpcma",
    "cslot1:ymsnd:adpcmb": "adpcmb", "cslot1:sprites": "sprites",
}
LOADS = {"ROM_LOAD": "Plain", "ROM_LOAD16_WORD_SWAP": "WordSwap16", "ROM_LOAD16_BYTE": "Byte16"}

# Button names for well-known games (A, B, C, D on the Neo Geo panel).
NAMES = {
    "mslug": ["Shoot", "Jump", "Grenade"], "mslug2": ["Shoot", "Jump", "Grenade"],
    "kof94": ["Light Punch", "Light Kick", "Heavy Punch", "Heavy Kick"],
    "kof95": ["Light Punch", "Light Kick", "Heavy Punch", "Heavy Kick"],
    "kof96": ["Light Punch", "Light Kick", "Heavy Punch", "Heavy Kick"],
    "kof97": ["Light Punch", "Light Kick", "Heavy Punch", "Heavy Kick"],
    "lastblad": ["Weak Slash", "Strong Slash", "Kick", "Deflect"],
    "lastbld2": ["Weak Slash", "Strong Slash", "Kick", "Deflect"],
    "samsho": ["Light Slash", "Medium Slash", "Light Kick", "Medium Kick"],
    "samsho2": ["Light Slash", "Medium Slash", "Light Kick", "Medium Kick"],
    "neobombe": ["Bomb", "Kick"], "pbobblen": ["Shoot"], "pbobbl2n": ["Shoot"],
    "blazstar": ["Shot", "Burst"], "pulstar": ["Shot", "Bomb"],
    "turfmast": ["Shot", "Club"], "twinspri": ["Shot", "Bomb"],
    "shocktro": ["Shoot", "Jump", "Bomb"], "viewpoin": ["Shot", "Bomb"],
    "nam1975": ["Shot", "Jump"], "sengoku": ["Attack", "Jump", "Change"],
    "sengoku2": ["Attack", "Jump", "Change"], "wh1": ["Light Punch", "Light Kick", "Heavy Punch", "Heavy Kick"],
}


def main(snk):
    src = open(snk + "/neogeo.cpp").read()
    macros = load_macros(src)
    print("// Generated by tools/gen_neogeo_games.py from MAME's Neo Geo driver (BSD-3-Clause,")
    print("// copyright-holders: Bryan McPhail, Ernesto Corvi, Andrew Prime, Zsolt Vasvari). Do not edit.")
    count = 0
    for gl in re.finditer(r'^GAME\(\s*(\d+),\s*(\w+)\s*,\s*neogeo\s*,\s*neobase\s*,\s*neogeo\s*,\s*\w+\s*,\s*empty_init\s*,'
                          r'\s*(ROT\d+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"', src, re.M):
        year, game, rot, maker, title = gl.groups()
        if game in SKIP:
            continue
        m = re.search(r"ROM_START\(\s*" + re.escape(game) + r"\s*\)(.*?)ROM_END", src, re.S)
        if not m:
            continue
        body = expand(m.group(1), macros)
        roms, regions, region, ok, why = [], {}, None, True, ""
        for t in re.finditer(r"\b(ROM_REGION\w*|ROM_LOAD\w*|ROM_CONTINUE|ROM_RELOAD|ROM_FILL|ROM_COPY)\s*\(", body):
            args = split_args(call_args(body, t.end() - 1)[0])
            kind = t.group(1)
            if kind.startswith("ROM_REGION"):
                region = REGION_NAMES.get(args[1].strip('"'))
                if args[1].strip('"') == "mainbios":
                    region = None
                elif region is None:
                    ok = False  # unknown region: some special cartridge
                    why = "region " + args[1]
                    break
                else:
                    regions[region] = num(args[0])
                continue
            if region is None:
                continue
            if kind == "ROM_RELOAD":
                if region != "audiocpu":
                    ok = False
                continue  # the machine maps the Z80 banks itself
            if kind in ("ROM_FILL", "ROM_COPY") or (kind.startswith("ROM_LOAD") and kind not in LOADS):
                ok = False
                why = kind
                break
            if kind == "ROM_CONTINUE":
                roms.append(f'{{"{region}", nullptr, 0, {args[0]}, {args[1]}, RomLoad::Continue}}')
                continue
            crc = re.search(r"CRC\((\w+)\)", args[3] if len(args) > 3 else "")
            if not crc:
                ok = False
                why = "no crc " + str(args)
                break
            roms.append(f'{{"{region}", {args[0]}, 0x{crc.group(1).lower()}, {args[1]}, {args[2]}, RomLoad::{LOADS[kind]}}}')
        if not ok or "sprites" not in regions or "maincpu" not in regions:
            print(f"// skipped {game}: {why or sorted(regions)}", file=sys.stderr)
            continue
        clean = re.sub(r"\s*\([^)]*\)\s*$", "", title).replace('"', '\\"')
        names = NAMES.get(game, ["A", "B", "C", "D"])
        print(f"{{   // {title}")
        print("    Def g;")
        print(f'    g.info.set = "{game}"; g.info.parent = "neogeo"; g.info.title = "{clean}";')
        print(f'    g.info.year = "{year}"; g.info.manufacturer = "{maker}"; g.info.rotation = {rot[3:]};')
        print("    g.info.buttonNames = {" + ", ".join(f'"{n}"' for n in names) + "};")
        print("    g.regionSizes = {" + ", ".join(f'{{"{k}", {hex(v)}}}' for k, v in regions.items()) + "};")
        print("    g.roms = {")
        for r in roms:
            print(f"        {r},")
        print("    };")
        print("    v.push_back(std::move(g));")
        print("}")
        count += 1
    print(f"// {count} games", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
