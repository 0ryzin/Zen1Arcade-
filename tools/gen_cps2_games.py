"""Generates machines/cps1/cps2_games_data.inc from MAME's CPS-2 driver.

Usage: tools/gen_cps2_games.py /path/to/mame/src/mame/capcom > machines/cps1/cps2_games_data.inc

Takes every CPS-2 set that runs on the standard board in MAME ("cps2" or
"dead_cps2" machine, init_cps2, a standard joystick-and-buttons control
panel): title, year, maker, players, buttons and the ROM list (files, CRCs,
offsets, layouts) including the decryption key file of the set. Data is
MAME's (BSD-3-Clause, copyright-holders: Paul Leaman, Andreas Naive, Nicola
Salmoria); see machines/cps1/LICENSE-MAME-BSD-3-Clause.txt.
"""
import re
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from gen_cps1_games import LOADS, num  # noqa: E402

INPUTS = {  # MAME input set -> (players, buttons)
    "cps2_1p2b": (1, 2), "cps2_2p1b": (2, 1), "cps2_2p2b": (2, 2), "cps2_2p3b": (2, 3),
    "cps2_2p6b": (2, 6), "cps2_3p3b": (3, 3), "cps2_4p2b": (4, 2), "cps2_4p3b": (4, 3),
    "cps2_4p4b": (4, 4), "cybots": (2, 4),
}
SIX = ["Light Punch", "Medium Punch", "Heavy Punch", "Light Kick", "Medium Kick", "Heavy Kick"]
NAMES = {
    "ddtod": ["Attack", "Jump", "Select", "Use"], "ddsom": ["Attack", "Jump", "Select", "Use"],
    "avsp": ["Attack", "Jump", "Shot"], "armwar": ["Attack", "Jump", "Special"],
    "19xx": ["Shot", "Bomb"], "1944": ["Shot", "Bomb"], "gigawing": ["Shot", "Force Bomb"],
    "progear": ["Shot", "Bomb", "Auto"], "dimahoo": ["Shot", "Bomb", "Auto"], "mmatrix": ["Shot"],
    "batcir": ["Attack", "Jump"], "spf2t": ["Rotate Left", "Rotate Right"], "mpang": ["Shot"],
    "megaman2": ["Shot", "Jump", "Special"], "sgemf": ["Punch", "Kick", "Special"],
    "cybots": ["Light Attack", "Heavy Attack", "Boost", "Weapon"], "csclub": ["Button 1", "Button 2", "Button 3"],
    "sfz2al": SIX,
}
SKIP_GAMES = {"ecofghtr", "qndream", "pzloop2", "choko", "jyangoku"}  # dial, quiz, paddle, mahjong panels
REGIONS = {"maincpu", "gfx", "audiocpu", "qsound", "key"}


def main(capcom):
    src = open(capcom + "/cps2.cpp").read()
    games = []
    for gl in re.finditer(r'^GAME\(\s*(\d+),\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*cps2_state\s*,\s*(\w+)\s*,'
                          r'\s*(ROT\d+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"', src, re.M):
        year, game, parent, machine, inputs, init, rot, maker, title = gl.groups()
        if machine not in ("cps2", "dead_cps2") or init != "init_cps2" or inputs not in INPUTS:
            continue
        root = game if parent == "0" else parent
        if root in SKIP_GAMES or game in SKIP_GAMES:
            continue
        games.append((year, game, "" if parent == "0" else parent, inputs, rot, maker, title, machine))
    parents = {g[1] for g in games if not g[2]}
    games = [g for g in games if not g[2] or g[2] in parents]

    print("// Generated by tools/gen_cps2_games.py from MAME's CPS-2 driver (BSD-3-Clause,")
    print("// copyright-holders: Paul Leaman, Andreas Naive, Nicola Salmoria). Do not edit by hand.")
    for year, game, parent, inputs, rot, maker, title, machine in games:
        players, buttons = INPUTS[inputs]
        root = parent or game
        names = NAMES.get(root) or (SIX if buttons == 6 else [f"Button {i + 1}" for i in range(buttons)])
        names = names[:buttons]
        block = re.search(r"ROM_START\(\s*" + re.escape(game) + r"\s*\)(.*?)ROM_END", src, re.S).group(1)
        roms, region, sizes = [], None, {}
        ok = True
        for line in block.splitlines():
            line = line.split("//")[0]
            r = re.search(r'ROM_REGION\w*\(\s*([^,]+),\s*"(\w+)"', line)
            if r:
                region = r.group(2)
                size = r.group(1).strip()
                sizes[region] = {"CODE_SIZE": 0x400000, "QSOUND_SIZE": 0x50000}.get(size) or num(size)
                continue
            if region not in REGIONS:
                continue
            r = re.search(r'(ROM_LOAD\w*)\(\s*"([^"]+)",\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*CRC\((\w+)\)', line)
            if r:
                if r.group(1) not in LOADS:
                    ok = False
                    break
                roms.append(f'{{"{region}", "{r.group(2)}", 0x{r.group(5).lower()}, {r.group(3)}, {r.group(4)}, '
                            f'RomLoad::{LOADS[r.group(1)]}}}')
                continue
            r = re.search(r"ROM_CONTINUE\(\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)", line)
            if r:
                roms.append(f'{{"{region}", nullptr, 0, {r.group(1)}, {r.group(2)}, RomLoad::Continue}}')
                continue
            r = re.search(r"ROM_FILL\(\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)", line)
            if r and num(r.group(3)) == 0:
                continue  # regions start zero-filled
            if "ROM_FILL" in line or "ROM_COPY" in line or "NO_DUMP" in line:
                ok = False
                break
        if not ok or "key" not in sizes or not roms:
            continue
        clean = title if parent else re.sub(r"\s*\([^)]*\)\s*$", "", title)
        names_cpp = ", ".join(f'"{n}"' for n in names)
        print(f"\n{{   // {title}")
        print("    GameDef g;")
        print(f'    g.info.set = "{game}"; g.info.parent = "{parent}"; g.info.title = "{clean}";')
        print(f'    g.info.year = "{year}"; g.info.manufacturer = "{maker}"; g.info.system = "Capcom CPS-2";')
        print(f'    g.info.players = {players}; g.info.buttons = {buttons}; g.info.rotation = {rot[3:]};')
        print('    g.info.joystick = "8-way";')
        print(f"    g.info.buttonNames = {{{names_cpp}}};")
        print("    g.cps2 = true;" + (" g.cps2Dead = true;" if machine == "dead_cps2" else ""))
        print(f"    g.gfxRegionSize = {hex(sizes.get('gfx', 0))};")
        print(f"    g.qsoundRegionSize = {hex(sizes.get('qsound', 0))};")
        print("    g.roms = {")
        for r in roms:
            print(f"        {r},")
        print("    };")
        print("    d.push_back(std::move(g));")
        print("}")


if __name__ == "__main__":
    main(sys.argv[1])
